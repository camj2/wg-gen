use crate::{Error, Result};
use crate::{IpPrefix, Ipv6Prefix};

use wireguard_keys::{Privkey as PrivateKey, Secret as PresharedKey}; // TO-DO: write custom key gen crate

use serde::{Deserialize, Serialize};

use std::collections::BTreeMap;
use std::fmt;
use std::fs;
use std::fs::File;
use std::io::Write;
use std::path::Path;

// Thought: Support IPv4, but only apply IPv4 addresses to the first 255 peers.

#[derive(Deserialize, Serialize)]
pub struct Config {
    // Base address.
    ip: IpPrefix,

    // Peer address is derived from the map key.
    peers: BTreeMap<u64, Peer>,
}

#[derive(Deserialize, Serialize)]
struct Peer {
    // Alias. Used by Unbound for domain name resolution.
    name: String,

    // WireGuard base64 private key.
    private_key: PrivateKey,

    // WireGuard base64 preshared key. Generated by default for extra security.
    preshared_key: Option<PresharedKey>,

    // IP or hostname, followed by a colon, and then a port number. Required for the server peer.
    endpoint: Option<String>,

    // Required when an endpoint is set (see above). 51820 is the WireGuard default.
    listen_port: Option<u16>,

    // If behind NAT, set to 25. Only required if peer needs to be accessible from the server peer.
    persistent_keepalive_interval: Option<u16>,

    // Mark for outgoing packets.
    fwmark: Option<u32>,

    // TO-DO: consider adding check to prevent values above 1500
    // Default value is 1420. Try a lower value if experiencing packet loss.
    mtu: Option<u16>,
}

impl Config {
    pub fn print(&self) {
        for (id, peer) in &self.peers {
            println!("{}: {}", id, peer.name)
        }
    }

    pub fn new() -> Self {
        let ip = IpPrefix::from(Ipv6Prefix::default().generate_ula().generate_network());

        let peers: BTreeMap<u64, Peer> = BTreeMap::new();

        Self { ip, peers }
    }

    pub fn add<T: fmt::Display>(&mut self, name: T) -> Result<()> {
        // Find lowest available slot.
        let id = (u64::MIN..u64::MAX)
            .into_iter()
            .find(|id| !self.peers.contains_key(id))
            .ok_or(Error::TooManyPeers)?;

        let private_key = PrivateKey::generate();
        let preshared_key = PresharedKey::generate();

        let peer = Peer {
            name: name.to_string(),
            private_key,
            preshared_key: Some(preshared_key),
            endpoint: None,
            listen_port: None,
            persistent_keepalive_interval: None,
            fwmark: None,
            mtu: None,
        };

        self.peers.insert(id, peer);

        Ok(())
    }

    pub fn del<T: fmt::Display>(&mut self, name: T) -> Result<()> {
        self.peers.retain(|_, peer| peer.name != name.to_string());

        Ok(())
    }

    pub fn from_path(path: &Path) -> Result<Self> {
        let file_contents = fs::read_to_string(&path)?;

        let config: Self = serde_json::from_str(&file_contents)?;

        Ok(config)
    }

    pub fn write_to_path(&self, path: &Path) -> Result<()> {
        let json = serde_json::to_string_pretty(&self)?;

        fs::write(&path, &json)?;

        Ok(())
    }

    // Build WireGuard config files.
    pub fn export_to_path(&self, path: &Path) -> Result<()> {
        // First entry is considered the "server" peer, remainder are "client" peers.
        let server_entry = self.peers.first_key_value().ok_or(Error::NoneFound)?;

        let server_id = *server_entry.0;
        let server = server_entry.1;

        let prefix = match &self.ip {
            IpPrefix::V4(_) => return Err(Error::V4NotSupported),
            IpPrefix::V6(ip) => ip,
        };

        // TO-DO: Check for duplicate names! Thought: Use BTreeMap for Unbound config? Reverse HashMap?

        // Create export directory
        fs::create_dir(&path)?;

        fs::create_dir(&path.join(""))?;

        // Server WireGuard config file
        let mut server_config = File::create(path.join("wireguard.conf"))?;

        // [Interface]
        writeln!(server_config, "[Interface]")?;

        // PrivateKey
        writeln!(server_config, "PrivateKey = {}", server.private_key)?;

        // Address
        writeln!(server_config, "Address = {}", prefix.int(server_id))?;

        // ListenPort
        if let Some(v) = server.listen_port {
            writeln!(server_config, "ListenPort = {}", v)?;
        }

        // FwMark
        if let Some(v) = server.fwmark {
            writeln!(server_config, "FwMark = {:#x}", v)?;
        }

        // MTU
        if let Some(v) = server.mtu {
            writeln!(server_config, "MTU = {}", v)?;
        }

        // Server Unbound config file
        let mut unbound_config = File::create(path.join("unbound.conf"))?;
        // TO-DO: rename to unbound_buf and write depending whether or not AAAA or A, IpPrefixDual ?

        // Unbound
        writeln!(unbound_config, "# {}", server.name)?;

        // AAAA Record
        writeln!(
            unbound_config,
            "local-data: '{} AAAA {}'",
            server.name,
            prefix.int(server_id).addr()
        )?;

        // PTR Record
        writeln!(
            unbound_config,
            "local-data-ptr: '{} {}'",
            prefix.int(server_id).addr(),
            server.name
        )?;

        for (id, peer) in &self.peers {
            let peer_id = *id;

            // Thought: Generate "server" peer here instead of above
            if peer_id == server_id {
                continue;
            }

            let name = format!("{}-{}.conf", peer_id, peer.name);

            // Client WireGuard config file
            let mut config = File::create(&path.join(name))?;

            // TO-DO:
            // Client WireGuard QR code file
            // let mut config = File::create(&path.join(name))?;

            // [Interface]
            writeln!(config, "[Interface]")?;

            // PrivateKey
            writeln!(config, "PrivateKey = {}", peer.private_key)?;

            // Address
            writeln!(config, "Address = {}", prefix.int(peer_id))?;

            // DNS
            writeln!(config, "DNS = {}", prefix.int(server_id).addr())?;

            // ListenPort
            if let Some(port) = peer.listen_port {
                writeln!(config, "ListenPort = {}", port)?;
            }

            // FwMark
            if let Some(mark) = peer.fwmark {
                writeln!(config, "FwMark = {:#x}", mark)?;
            }

            // MTU
            if let Some(mtu) = peer.mtu {
                writeln!(config, "MTU = {}", mtu)?;
            }

            // [Peer]
            writeln!(config, "\n[Peer]")?;

            // PublicKey
            writeln!(config, "PublicKey = {}", server.private_key.pubkey())?;

            // PresharedKey
            if let Some(key) = peer.preshared_key {
                writeln!(config, "PresharedKey = {}", key)?;
            }

            // AllowedIPs
            writeln!(config, "AllowedIPs = {}", prefix)?;

            // Endpoint
            if let Some(endpoint) = &server.endpoint {
                writeln!(config, "Endpoint = {}", endpoint)?;
            }

            // PersistentKeepalive
            if let Some(interval) = &peer.persistent_keepalive_interval {
                writeln!(config, "PersistentKeepalive = {}", interval)?;
            }

            // Server

            // [Peer]
            writeln!(server_config)?;
            writeln!(server_config, "# {}", peer.name)?;
            writeln!(server_config, "[Peer]")?;

            // PublicKey
            writeln!(server_config, "PublicKey = {}", peer.private_key.pubkey())?;

            // PresharedKey
            if let Some(key) = peer.preshared_key {
                writeln!(server_config, "PresharedKey = {}", key)?;
            }

            // AllowedIPs
            writeln!(server_config, "AllowedIPs = {}", prefix.int(peer_id))?;

            // Endpoint
            if let Some(endpoint) = &peer.endpoint {
                writeln!(server_config, "Endpoint = {}", endpoint)?;
            }

            // Unbound
            writeln!(unbound_config, "\n# {}", peer.name)?;

            // AAAA Record
            writeln!(
                unbound_config,
                "local-data: '{} AAAA {}'",
                peer.name,
                prefix.int(peer_id).addr()
            )?;

            // PTR Record
            writeln!(
                unbound_config,
                "local-data-ptr: '{} {}'",
                prefix.int(peer_id).addr(),
                peer.name,
            )?;
        }
        Ok(())
    }
}
